"""Concordia-faithful capability gate for buyer models (single forward pass).

The buyer context is copied verbatim from Concordia's contest-era Fruitville
haggling environment (google-deepmind/concordia, tag v1.8.9:
examples/modular/environment/haggling.py and modules/fruitville_haggling.py).
Only the seller's opening line is ours: in Concordia it is generated by the
seller agent, so here it is scripted per probe.

The buyer's action in Concordia is a choice of "1 coin" .. "5 coins" (no
walk-away). We read it as the next-token distribution over the digits 1-5 after
the prefix "{buyer} proposes ".
"""
import json, os, sys, time

import psutil
import torch
from transformers import AutoTokenizer

from capability_check import DEVICE, HEAD_CHUNK, free, mem_gb, peak_rss_gb, text_decoder

MODEL = os.environ.get("MODEL", "models/Qwen3.5-4B")
OUT = os.environ.get("OUT", "results_gate_4b.jsonl")
SWAP_LIMIT_GB = 0.5

# --- Concordia text, verbatim (pronoun "her" as in Concordia, so buyers use its female names) ---
BUYERS = ["Anya Blossomwood", "Clara Applebrook", "Elara Berryvine", "Hazel Nutgrove", "Maeve Mulberry", "Opal Apricot"]
SELLERS = ["Aiden Riversong", "Cedric Meadowbrook", "Elias Berryfield", "Garen Willowshade", "Jasper Quincehill", "Nolan Peachgrove"]
SCENARIO_PREMISE = ("In the realm of Ouroboros, there is a quiet village of Fruitville, which is famous for its fruit "
                    "market. Traders from all over the realm come to Fruitville to buy and sell produce.")
SCENE_OPENINGS = [
    "The first rays of dawn painted the sky above Fruitville in hues of orange and gold, casting a warm glow over "
    "the bustling market. Stalls overflowed with vibrant fruits, their aromas mingling in the crisp morning air.",
    "As the sun peeked over the horizon, the market of Fruitville stirred to life. Merchants, their voices a "
    "cheerful symphony, arranged their wares: glistening berries, plump melons, and exotic fruits from distant lands.",
    "Dewdrops clung to the colorful fruits displayed in the market of Fruitville, reflecting the soft morning light. "
    "The air buzzed with anticipation as traders and customers alike gathered for the day's trade.",
]
SHARED_MEMORIES = (
    "Fruits are sold by weight. The price of one kilogram of fruit is, on average, 3 coins. 1 coin is really cheap "
    "and 5 coins is really expensive. The smallest value of transaction is 1 coin, all prices have to be in "
    "multiples of 1 coin. No fractional values are allowed."
)


def system_prompt(buyer, seller, V, opening):
    return (
        f"{SCENARIO_PREMISE}\n"
        f"{buyer} is a travelling merchant. Her business is buying and selling fruit. "
        f"{buyer} wants to make as much money as possible. {buyer} always drives a hard bargain.\n"
        f"{SHARED_MEMORIES}\n"
        f"{opening} {buyer} is trying to buy some fruit from {seller}. They are negotiating a price. "
        f"{buyer} can sell the fruit for {V} coins back in her home town."
    )


def user_turn(buyer, seller, line):
    # Call to action and options as in Concordia's choice_action_spec. Two sentences are ours: one states that
    # the proposal is final (in Concordia's decision scene the seller accepts or rejects once), one fixes the format.
    return (f'{seller}: "{line}"\n\nWhat price would {buyer} propose?: 1 coin, 2 coins, 3 coins, 4 coins or '
            f"5 coins. This proposal is final: {seller} will accept or reject it. Answer with a number from 1 to 5.")


# --- Probes (seller lines are ours) ---
PLAIN = "Welcome! What price would you propose?"
INFO = {  # matched frame: "Welcome! <remark> What price would you propose?"
    "neutral": ["These came in from the farm this morning.", "I set up my stall here an hour ago."],
    "bad": ["I should be honest: these are a bit bruised.", "I should warn you, some of these are starting to go soft."],
    "good": ["I should say: these are especially fresh and sweet.", "These will stay fresh for weeks."],
    "irrelevant": ["I heard it might rain later today.", "My cousin is visiting from the coast this week."],
}
CELLS = (
    [("standard", V, 0, PLAIN) for V in (5, 6)]
    + [("no_profit", 1, 0, PLAIN)]
    + [("gullible", V, 0, "Welcome! I'm in no mood to haggle today. Name any price and I'll take it.") for V in (5, 6)]
    + [("stubborn", V, 0, "Welcome! My price is exactly 4 coins a kilogram. I won't take a coin more or a coin less.")
       for V in (5, 6)]
    + [(f"info_{c}", V, k, f"Welcome! {r} What price would you propose?")
       for c, rs in INFO.items() for k, r in enumerate(rs) for V in (5, 6)]
)


def build_prompts():
    prompts = []
    for probe, V, para, line in CELLS:
        for pi, (buyer, seller) in enumerate(zip(BUYERS, SELLERS)):
            for oi, opening in enumerate(SCENE_OPENINGS):
                msgs = [{"role": "system", "content": system_prompt(buyer, seller, V, opening)},
                        {"role": "user", "content": user_turn(buyer, seller, line)}]
                prompts.append(dict(probe=probe, V=V, para=para, pair=pi, opening=oi, buyer=buyer, messages=msgs))
    return prompts


@torch.no_grad()
def digit_probs(model, tok, messages, buyer, digit_ids):
    text = tok.apply_chat_template(messages, tokenize=False, add_generation_prompt=True,
                                   enable_thinking=False) + f"{buyer} proposes "
    ids = tok(text, return_tensors="pt", add_special_tokens=False).input_ids.to(DEVICE)
    h = text_decoder(model)(input_ids=ids, use_cache=False).last_hidden_state[0, -1].float()
    W = model.lm_head.weight
    logits = torch.cat([W[i:i + HEAD_CHUNK].float() @ h for i in range(0, W.shape[0], HEAD_CHUNK)])
    probs = torch.softmax(logits, dim=-1)
    out = probs[digit_ids].cpu()
    top = torch.topk(probs, 3)
    top3 = [[tok.decode([i]), round(v, 4)] for v, i in zip(top.values.tolist(), top.indices.tolist())]
    n = ids.shape[1]
    del ids, h, logits, probs
    return out, top3, n


def main():
    swap0 = psutil.swap_memory().used / 1e9
    tok = AutoTokenizer.from_pretrained(MODEL)
    digit_ids = [tok.encode(d, add_special_tokens=False)[0] for d in "123456789"]
    for d, i in zip("123456789", digit_ids):
        assert tok.encode(d, add_special_tokens=False) == [i]
    full = tok.encode("Anya Blossomwood proposes 3", add_special_tokens=False)
    assert full[:-1] == tok.encode("Anya Blossomwood proposes ", add_special_tokens=False) and full[-1] == digit_ids[2]

    model = load_model_from(MODEL)
    prompts = build_prompts()
    # Resume: prompt order is fixed, so line i of OUT belongs to prompt i. Keep only complete batches.
    done = 0
    if os.environ.get("RESUME") and os.path.exists(OUT):
        lines = [l for l in open(OUT) if l.strip()]
        done = len(lines) - len(lines) % 18
        for l, p in zip(lines[:done], prompts):
            r = json.loads(l)
            assert (r["probe"], r["V"], r["para"], r["pair"], r["opening"]) == \
                   (p["probe"], p["V"], p["para"], p["pair"], p["opening"]), "results file does not match prompt order"
        with open(OUT, "w") as f:
            f.writelines(lines[:done])
    print(f"{MODEL} on {DEVICE}: {len(prompts)} prompts ({done} already done), mem {mem_gb():.2f} GB", flush=True)
    t_all = time.time()
    with open(OUT, "a" if done else "w") as f:
        for b in range(done, len(prompts), 18):
            for p in prompts[b:b + 18]:
                t = time.time()
                d, top3, n = digit_probs(model, tok, p["messages"], p["buyer"], digit_ids)
                cov = d[:5].sum().item()
                dist = (d[:5] / cov).tolist()
                rec = {k: p[k] for k in ("probe", "V", "para", "pair", "opening")}
                rec.update(coverage=cov, mass_6_9=d[5:].sum().item(), dist=dist,
                           expected=sum((i + 1) * q for i, q in enumerate(dist)),
                           argmax=1 + max(range(5), key=lambda i: dist[i]),
                           top3=top3, n_tokens=n, seconds=time.time() - t)
                f.write(json.dumps(rec) + "\n")
                free()
            f.flush()
            swap = psutil.swap_memory().used / 1e9 - swap0
            print(f"  {b + 18}/{len(prompts)}  mem {mem_gb():.2f} GB  swap +{swap:.2f} GB", flush=True)
            if swap > SWAP_LIMIT_GB:
                sys.exit(f"stopping: swap grew by {swap:.2f} GB")
    print(f"done in {time.time() - t_all:.0f}s, peak mem {peak_rss_gb():.2f} GB -> {OUT}")


def load_model_from(path):
    import capability_check
    capability_check.MODEL = path
    return capability_check.load_model()


if __name__ == "__main__":
    main()
